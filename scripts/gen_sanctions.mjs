// Build src/sanctions-data.ts from data/ofac_sdn_evm.txt (the same snapshot the Python SDK bundles).
import { readFileSync, writeFileSync } from "node:fs";
const text = readFileSync(new URL("../data/ofac_sdn_evm.txt", import.meta.url), "utf8");
let asOf = "unknown";
const addrs = [];
for (const raw of text.split("\n")) {
  const line = raw.trim();
  if (!line) continue;
  if (line.startsWith("#")) { const m = line.match(/as_of:\s*(\S+)/); if (m) asOf = m[1]; continue; }
  if (!/^0x[0-9a-fA-F]{40}$/.test(line)) throw new Error(`bad line: ${line}`);
  addrs.push(line.toLowerCase());
}
const header = text.split("\n").filter((l) => l.startsWith("#")).map((l) => "// " + l.slice(1).trim()).join("\n");
writeFileSync(new URL("../src/sanctions-data.ts", import.meta.url),
  `${header}\n// Generated by scripts/gen_sanctions.mjs. Do not edit by hand.\n` +
  `export const BUNDLED_AS_OF = ${JSON.stringify(asOf)};\n` +
  `export const BUNDLED_SANCTIONS: readonly string[] = ${JSON.stringify([...new Set(addrs)], null, 0)};\n`);
console.log(`${new Set(addrs).size} addresses, as of ${asOf}`);
